/**
 * build-base44-markets.js — write the website's read-markets.js, which reads
 * the GNK price in the visitor's browser, from the app's own code.
 *
 *   node scripts/build-base44-markets.js [outfile]
 *
 * The app reads the four GNK markets from the computer it runs on. The
 * website's server cannot do that reliably: the markets limit how often one
 * address may ask, and Base44's servers share theirs with many other websites
 * (on 28 October 2026 not one market answered them for hours). Every market
 * lets a web page read it, so the website reads them as the app does, from the
 * visitor's own computer, and sends what it read to its functions
 * (scripts/base44-price.js). This is the app's src/services/earnings.js
 * gnkPrice and getJson, unchanged but for one thing: a market gets 6 seconds
 * to answer instead of 15, so a slow one cannot hold a page up.
 */
const fs = require("fs");
const path = require("path");
const E = require("../src/services/earnings")._parts;

const out = process.argv[2] || path.join(__dirname, "..", "docs", "base44", "read-markets.js");
const getJson = E.getJson.toString();
if (!/timeout = 15000/.test(getJson)) throw new Error("earnings.js getJson no longer waits 15000 ms by default: look at this script again");

const code = `// read-markets.js — the GNK price markets, read in the visitor's browser
// exactly as the GNOT app reads them on the user's computer.
//
// GENERATED by scripts/build-base44-markets.js from the GNOT app's own
// src/services/earnings.js (gnkPrice) in
// github.com/gonkanetworkonboardinghub/gonka-network-onboarding-tool. Do not
// edit it here: change the app's code, run the script again, and paste the new file.
//
// readMarkets() -> [{ name, usd }], one per market that answered (none: []).
// Send it as "markets" with every call to the gnot-monitor and gnot-rentals
// functions; they work the price out from it, as the app does. One reading is
// shared by the whole page for five minutes (one minute when no market answered).

const WGNK = ${JSON.stringify(E.WGNK)};

// A market gets 6 seconds here (15 in the app), so a slow one cannot hold the page up.
${getJson.replace("timeout = 15000", "timeout = 6000")}

${E.gnkPrice.toString()}

let reading = null;   // { at, sources }
export function readMarkets() {
  const keep = reading && reading.sources && reading.sources.length ? 5 * 60 * 1000 : 60 * 1000;
  if (!reading || Date.now() - reading.at > keep) {
    const r = { at: Date.now(), sources: null };
    r.pending = gnkPrice().then((p) => (r.sources = p.sources || [])).catch(() => (r.sources = []));
    reading = r;
  }
  return reading.pending;
}
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, code);
new Function(code.replace(/^export /m, ""));   // it must at least parse
console.log(`${out}: ${code.split("\n").length} lines`);
