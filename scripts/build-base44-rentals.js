/**
 * build-base44-rentals.js — write the website's "gnot-rentals" Base44 function
 * from the app's own code.
 *
 *   node scripts/build-base44-rentals.js [outfile]
 *
 * The website's Mine or buy page shows what the app's Mine-or-buy panel
 * shows: what each rig earns, and what renting one costs at each provider. A
 * web page cannot ask the Gonka nodes (plain http, which a secure page may not
 * call) or Spheron (it answers an error to requests from another website), so
 * the page asks this server function, which can. It must work everything out
 * exactly as the app does, so it is not written by hand: this puts the app's
 * src/services/earnings.js, netdata.js and rentals.js in it whole, unchanged,
 * and works the figures out live from the network, with the same ten-minute
 * reading the app keeps. Change the app's code, run this again, and paste the
 * new file into Base44.
 *
 * Two things the website's server cannot always have, and what stands in:
 *   - GNK price: markets limit how often one address may ask, and this server
 *     shares its address with many other websites. Each market that does not
 *     answer is taken from the data job's last reading of it (earnings.json;
 *     scripts/base44-price.js), and the middle of all four is taken, as the app.
 *   - Gonka's setup files: GitHub's API also limits a shared address. When it
 *     will not list them, the setups the data job last listed stand in.
 * Should the network not answer at all, the data job's last earnings.json is
 * answered, marked earningsLive: false.
 *
 * GET -> { asOf, providers, price, earningsAsOf, earningsLive, earnings }
 *   providers is the rentals comparison (as rentals.json); earnings is the
 *   app's earnings figures (as earnings.json), from the same reading.
 */
const fs = require("fs");
const path = require("path");
const K = require("../src/knowledge");
const { fillInPrice } = require("./base44-price");

const out = process.argv[2] || path.join(__dirname, "..", "docs", "base44", "gnot-rentals.js");
const k = K.get();
const src = (file) => fs.readFileSync(path.join(__dirname, "..", "src", "services", file), "utf8").trim();
// What the three files read from knowledge.js, written as code so the patterns stay patterns.
const knowledge = `{
  seedNodes: ${JSON.stringify(k.seedNodes)},
  epochsUrl: ${JSON.stringify(k.epochsUrl)},
  repo: ${JSON.stringify(k.repo)},
  gpuClasses: [${k.gpuClasses.map((c) => `{ id: ${JSON.stringify(c.id)}, match: ${c.match.toString()} }`).join(", ")}],
  curatedConfigs: ${JSON.stringify(k.curatedConfigs)},
  requirements: ${JSON.stringify(k.requirements)}
}`;
const wrap = (name, file) => `const ${name} = (() => {
  const module = { exports: {} };
  const require = need;
${src(file)}
  return module.exports;
})();`;

const code = `// gnot-rentals — the website's live Mine or buy: what each rig earns and what renting one costs.
//
// GENERATED by scripts/build-base44-rentals.js from the GNOT app's own code
// (src/services/earnings.js, netdata.js and rentals.js, whole and unchanged)
// in github.com/gonkanetworkonboardinghub/gonka-network-onboarding-tool, so the
// website works out every figure live, exactly as the app does. Do not edit
// it here: change the app's code, run the script again, and paste the new file.
//
// GET -> { asOf, providers, price, earningsAsOf, earningsLive, earnings }
//   earnings: what each rig earns (the same shape as earnings.json)
//   providers: what renting each rig costs, compared with those earnings

const EARNINGS_URL = ${JSON.stringify(k.epochsUrl.replace(/epochs\.json$/, "earnings.json"))};

// What the app knows about the network, as its knowledge.js has it.
const KNOWLEDGE = ${knowledge};
const modules = {};
const need = (name) => (name === "../knowledge" ? { get: () => KNOWLEDGE } : name === "./netdata" ? modules.netdata : {});

// ---- the app's src/services/netdata.js, as it is ----
${wrap("Netdata", "netdata.js")}
modules.netdata = Netdata;
// ---- the app's src/services/earnings.js, as it is ----
${wrap("Earnings", "earnings.js")}
// ---- the app's src/services/rentals.js, as it is ----
${wrap("Rentals", "rentals.js")}
// ---- end of the app's code ----

// The data job's last earnings.json: the price of each market that does not
// answer here, the setups when GitHub will not list them, and the whole
// answer should the network not answer at all. Read at most every ten minutes.
let published = { at: 0, f: null };
async function publishedEarnings() {
  if (!published.f || Date.now() - published.at > 10 * 60 * 1000) {
    try { published = { at: Date.now(), f: await (await fetch(EARNINGS_URL, { signal: AbortSignal.timeout(15000) })).json() }; }
    catch (_) { /* keep the last one */ }
  }
  return published.f;
}

${fillInPrice.toString()}

// Gonka's setup files, from GitHub's API as the app reads them. GitHub limits
// how often one address may ask, so a listing is kept for an hour, and when
// none can be had the setups the data job last listed stand in.
const listSetups = Netdata.repoGpuConfigs;
let setups = { at: 0, rows: null };
Netdata.repoGpuConfigs = async () => {
  if (setups.rows && Date.now() - setups.at < 60 * 60 * 1000) return setups.rows;
  try {
    const rows = await listSetups();
    if (rows.length) { setups = { at: Date.now(), rows }; return rows; }
  } catch (_) { /* refused or unreachable */ }
  if (setups.rows) return setups.rows;
  const f = await publishedEarnings();
  return !f ? [] : [...(f.configs || []).filter((c) => c.deployable !== false && !(c.copies > 1)), ...(f.noHosts || []).filter((c) => !(c.copies > 1))]
    .map((c) => ({ file: "published", gpuClass: c.gpuClass, model: c.model, gpuCount: c.gpuCount }));
};

/** The earnings, live from the first of Gonka's public nodes that answers, as the data job reads them. */
async function earningsNow() {
  let last = null;
  for (const seed of KNOWLEDGE.seedNodes) {
    try {
      const e = await Earnings.estimate(seed);
      if ((e.configs || []).length) return { e, live: true };
    } catch (err) { last = err; }
  }
  const f = await publishedEarnings();
  if (f) return { e: JSON.parse(JSON.stringify(f)), live: false };
  throw last || new Error("no Gonka node answered");
}

let kept = null, pending = null;
async function answer() {
  const [{ e, live }, pub] = await Promise.all([earningsNow(), publishedEarnings()]);
  const earnings = JSON.parse(JSON.stringify(e));
  // The price as the app has it: the middle of four markets, each one that did
  // not answer this server taken from the data job's last reading of it.
  const price = fillInPrice(earnings.price, pub && pub.price && { ...pub.price, asOf: pub.asOf });
  earnings.price = price;
  for (const c of earnings.configs || []) {
    c.usdPerDay = price.usd ? c.gnkPerDay * price.usd : null;
    c.breakEvenPerHour = price.usd ? c.usdPerDay / 24 : null;
  }
  // Setups the network does not pay for: named as the data job last named them when GitHub would not list the setups.
  if (!(earnings.withoutData || []).length && pub && setups.rows === null) earnings.withoutData = pub.withoutData || [];
  const rentals = await Rentals.estimate(earnings, { force: true });
  return JSON.stringify({ ...rentals, price, earningsAsOf: earnings.asOf, earningsLive: live, earnings });
}

Deno.serve(async (req) => {
  const headers = { "Content-Type": "application/json", "Access-Control-Allow-Origin": "*", "Access-Control-Allow-Headers": "*", "Cache-Control": "public, max-age=60" };
  if (req.method === "OPTIONS") return new Response(null, { headers });
  // One answer a minute; visitors asking at the same moment share it.
  if (kept && Date.now() - kept.at < 60 * 1000) return new Response(kept.body, { headers });
  try {
    if (!pending) pending = answer().finally(() => { pending = null; });
    const body = await pending;
    kept = { at: Date.now(), body };
    return new Response(body, { headers });
  } catch (e) {
    return new Response(JSON.stringify({ error: String((e && e.message) || e) }), { status: 502, headers });
  }
});
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, code);
new (require("vm").Script)(code);   // it must at least parse
console.log(`${out}: ${code.split("\n").length} lines`);
