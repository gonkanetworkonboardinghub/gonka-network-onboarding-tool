/**
 * build-base44-rentals.js — write the website's "gnot-rentals" Base44 function
 * from the app's own code.
 *
 *   node scripts/build-base44-rentals.js [outfile]
 *
 * A web page cannot read Spheron's price list (Spheron answers an error to
 * requests from another website) or the Gonka nodes (plain http, which a
 * secure page may not call), so the website asks its own Base44 server
 * function, which can. That function must compare exactly as the app does, so
 * it is not written by hand: this takes the very functions the app runs
 * (src/services/rentals.js, and the GNK price from src/services/earnings.js)
 * and puts them in one file for Base44. Change the app's code, run this
 * again, and paste the new file into Base44.
 *
 * What the function does on each call (at most once a minute; it keeps the
 * answer for 60 s): reads the published earnings.json, the GNK price from the
 * same four sources as the app, and every provider's offers, and answers with
 * the same shape as rentals.json ({ asOf, providers: [...] }) plus the price.
 */
const fs = require("fs");
const path = require("path");
const K = require("../src/knowledge");
const R = require("../src/services/rentals")._parts;
const E = require("../src/services/earnings")._parts;
const { fillInPrice } = require("./base44-price");

const out = process.argv[2] || path.join(__dirname, "..", "docs", "base44", "gnot-rentals.js");
const earningsUrl = K.get().epochsUrl.replace(/epochs\.json$/, "earnings.json");
const regex = (re) => re.toString();

const src = `// gnot-rentals — the website's live "Compare with providers" figures.
//
// GENERATED by scripts/build-base44-rentals.js from the GNOT app's own code
// (src/services/rentals.js and the GNK price in src/services/earnings.js) in
// github.com/gonkanetworkonboardinghub/gonka-network-onboarding-tool, so the
// website compares exactly as the app does. Do not edit it here: change the
// app's code, run the script again, and paste the new file.
//
// GET -> { asOf, price, earningsAsOf, providers: [{ id, name, site, at, offers, error, rows }] }

const EARNINGS_URL = ${JSON.stringify(earningsUrl)};

// The GNK price, worked out as the app does.
const gnkPrice = (() => {
  const WGNK = ${JSON.stringify(E.WGNK)};
  ${E.getJson.toString()}
  return ${E.gnkPrice.toString()};
})();

${fillInPrice.toString()}

// The comparison, as the app does it.
const Rentals = (() => {
  const K = { get: () => ({ requirements: ${JSON.stringify(K.get().requirements)} }) };
  const KINDS = [${R.KINDS.map(([re, id]) => `[${regex(re)}, ${JSON.stringify(id)}]`).join(", ")}];
  const NOT_THESE = ${regex(R.NOT_THESE)};
  const MIN_GPU_GB = ${JSON.stringify(R.MIN_GPU_GB)};
  const CACHE_MS = 60 * 1000;
  let cache = null;
  ${R.getJson.toString()}
  const kindOf = ${R.kindOf.toString()};
  ${R.cudaAtLeast.toString()}
  ${R.newestCuda.toString()}
  ${R.spheron.toString()}
  const PROVIDERS = [${R.PROVIDERS.map((p) => `{ id: ${JSON.stringify(p.id)}, name: ${JSON.stringify(p.name)}, site: ${JSON.stringify(p.site)}, read: ${p.read.name} }`).join(", ")}];
  ${R.shortOf.toString()}
  ${R.compare.toString()}
  const lastCount = {};
  const THIN_RETRIES = ${R.THIN_RETRIES};
  const THIN_WAIT_MS = ${R.THIN_WAIT_MS};
  ${R.readFull.toString()}
  ${R.estimate.toString()}
  return { estimate };
})();

let kept = null;
Deno.serve(async (req) => {
  const headers = { "Content-Type": "application/json", "Access-Control-Allow-Origin": "*", "Cache-Control": "public, max-age=60" };
  if (req.method === "OPTIONS") return new Response(null, { headers });
  if (kept && Date.now() - kept.at < 60 * 1000) return new Response(kept.body, { headers });
  try {
    const earnings = await (await fetch(EARNINGS_URL, { signal: AbortSignal.timeout(15000) })).json();
    // The price as the app has it: the middle of four markets, each market that
    // did not answer this server taken from the data job's last reading of it
    // (scripts/base44-price.js).
    const price = fillInPrice(await gnkPrice(), earnings.price && { ...earnings.price, asOf: earnings.asOf });
    // What each rig may cost per hour at the price right now, as the app works it out.
    if (price.usd) for (const c of earnings.configs || []) {
      c.usdPerDay = c.gnkPerDay * price.usd;
      c.breakEvenPerHour = c.usdPerDay / 24;
    }
    const data = await Rentals.estimate(earnings, { force: true });
    const body = JSON.stringify({ ...data, price, earningsAsOf: earnings.asOf });
    kept = { at: Date.now(), body };
    return new Response(body, { headers });
  } catch (e) {
    return new Response(JSON.stringify({ error: String(e && e.message || e) }), { status: 502, headers });
  }
});
`;

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, src);
new (require("vm").Script)(src);   // it must at least parse
console.log(`${out}: ${src.split("\n").length} lines`);
